#!/usr/bin/env python3
"""Mirror-drift check between a Floot project and this repo's floot/ folder.

Floot has no export API, so the Floot side comes from two saved Floot MCP outputs:
  --listing  the text of list_files (lines "path (N chars)", plus the "version:" and "dependencies:" lines)
  --dumps    a folder of saved read_files results (plain text or the JSON wrapper), covering every listed file

  python3 tools/floot-drift.py --listing L.txt --dumps DIR            # report, exit 1 on any real difference
  python3 tools/floot-drift.py --listing L.txt --dumps DIR --write    # also refresh floot/ from Floot
  python3 tools/floot-drift.py --self-test

Ignored on purpose (export-only differences): the platform @layer base block the export appends to base.css,
blank lines at either end, env.json placeholders, and the shell files the export generates (App.tsx, index.html, ...).
Floot's generated static/__dev/history.md (read with the dumps) tells whether the current version is published;
unpublished work counts as a real difference unless --allow-unpublished.
Exit codes: 0 no real difference, 1 real differences, 2 the Floot input is incomplete (fix the dumps first).
"""
import argparse, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
# Repo-only files in floot/: generated by the export or kept by hand, never in list_files.
SHELL = {"App.tsx", "README.md", "global.css", "index.html", "index.tsx", "loadEnv.js",
         "package.json", "server.ts", "vite.config.ts", "env.json", "pnpm-lock.yaml"}
SKIP_DIRS = {"node_modules", "dist"}
HDR = re.compile(r"^(\S.*?) — lines (\d+)-(\d+) of (\d+) \(version: (\d+)\)$")
LINE = re.compile(r"^ *\d+\t(.*)$")
READ_CAP = 39500  # read_files returns at most ~40k chars of one file (line numbers included); smaller files must be dumped
LISTED = re.compile(r"^(\S.*) \((\d+) chars\)$")
# A comment (optional) then the platform @layer base block, at the very end of the repo's base.css.
LAYER_TAIL = re.compile(r"^\s*(/\*.*?\*/\s*)?@layer base\s*\{.*\}\s*$", re.S)


def parse_dump(text):
    """read_files output (cat -n blocks) -> {path: (content, version, complete)}."""
    if text.lstrip().startswith("["):  # tool result saved as JSON content blocks
        text = "\n".join(b.get("text", "") for b in json.loads(text) if isinstance(b, dict))
    out, cur, lines = {}, None, []
    def close():
        if cur: out[cur[0]] = ("\n".join(lines), cur[1], cur[2])
    for raw in text.split("\n"):
        m = HDR.match(raw)
        if m:
            close(); lines = []
            a, b, n = int(m.group(2)), int(m.group(3)), int(m.group(4))
            cur = (m.group(1), m.group(5), a == 1 and b == n)
            continue
        if raw == "# Project history":  # generated history comes back as plain text, without a header or line numbers
            close(); lines = [raw]; cur = ("static/__dev/history.md", "", False); continue
        if cur is None: continue
        if cur[0] == "static/__dev/history.md": lines.append(raw); continue
        lm = LINE.match(raw)
        if lm: lines.append(lm.group(1))
        elif raw.startswith("... (output capped"): cur = (cur[0], cur[1], False); close(); cur = None  # per-file cap
        elif raw.startswith("(omitted"): close(); cur = None
    close()
    return out


def parse_listing(text):
    files, deps, version = {}, {}, None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("version:"): version = line.split(":", 1)[1].strip()
        elif line.startswith("dependencies:"):
            for spec in line.split(":", 1)[1].split(" — ")[0].split(","):
                name, _, ver = spec.strip().rpartition("@")
                if name: deps[name] = ver
        else:
            m = LISTED.match(line)
            if m and not m.group(1).endswith("history.md"): files[m.group(1)] = int(m.group(2))
    return files, deps, version


def norm(s): return s.strip("\n")  # blank lines at either end are export noise


def same(path, floot, repo):
    """True when the repo copy matches Floot, allowing only the known export-only differences."""
    if norm(floot) == norm(repo): return True
    if path == "base.css" and norm(repo).startswith(norm(floot)):
        return bool(LAYER_TAIL.match(norm(repo)[len(norm(floot)):]))
    return False


def base_css_tail(repo):
    m = re.search(r"\n(\s*(/\*.*?\*/\s*)?@layer base\s*\{.*\}\s*)$", repo, re.S)
    return m.group(1) if m else ""


def repo_files(mirror):
    found = set()
    for d, dirs, names in os.walk(mirror):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for n in names:
            rel = os.path.relpath(os.path.join(d, n), mirror).replace(os.sep, "/")
            if rel not in SHELL: found.add(rel)
    return found


def read(p):
    with open(p, encoding="utf-8") as f: return f.read()


def unpublished(history):
    """True when Floot's generated history shows work newer than the latest publish (None if unknown)."""
    for line in history.splitlines():
        if line.startswith("── Published"): return False
        if line.startswith("## Checkpoint") or line.startswith("- "): return True
    return None


def check(listing, dumps_dir, mirror, write=False, allow_unpublished=False):
    files, deps, version = parse_listing(read(listing))
    floot, history, capped = {}, None, set()
    for name in sorted(os.listdir(dumps_dir)):
        for path, rec in parse_dump(read(os.path.join(dumps_dir, name))).items():
            if path.endswith("__dev/history.md"): history = rec[0]  # generated; only its top matters
            elif not rec[2]: capped.add(path)
            elif path not in floot or rec[1] > floot[path][1]: floot[path] = rec
    problems, size_only = [], []  # problems = incomplete Floot input
    added, changed, removed, notes = [], [], [], []
    for path, size in sorted(files.items()):
        repo_path = os.path.join(mirror, path)
        repo = read(repo_path) if os.path.exists(repo_path) else None
        if path not in floot:
            # shortcut: a file over Floot's per-file read cap (40k chars; 1,000 lines unless limit=5000) can't be dumped whole; equal size is
            # accepted as unchanged but reported. Upgrade if such a file starts changing.
            if (size > READ_CAP or path in capped) and repo is not None and abs(len(repo) - size) <= 1:  # 1 = a trailing newline either way
                size_only.append(path if len(repo) == size else f"{path} (sizes differ by 1, likely a trailing newline)"); continue
            problems.append(f"{path}: not in the dumps"); continue
        content = floot[path][0]
        if len(content) != size and len(content) + 1 != size:  # +1: a dump can't show a lone final newline
            problems.append(f"{path}: dump has {len(content)} chars, listing says {size}"); continue
        if repo is None: added.append(path)
        elif not same(path, content, repo): changed.append(path)
    removed = sorted(repo_files(mirror) - set(files))
    if write and not problems:  # never write from a partial read
        for path in added + changed:
            repo_path, content = os.path.join(mirror, path), floot[path][0]
            body = content + ("\n" if len(content) + 1 == files[path] else "")
            if path == "base.css" and os.path.exists(repo_path): body = norm(body) + "\n" + base_css_tail(read(repo_path))
            os.makedirs(os.path.dirname(repo_path), exist_ok=True)
            with open(repo_path, "w", encoding="utf-8", newline="") as f: f.write(body)
        for path in removed: os.remove(os.path.join(mirror, path))
    # Pages need a hand-made route in floot/App.tsx; a new page without one ships unreachable.
    app = read(os.path.join(mirror, "App.tsx")) if os.path.exists(os.path.join(mirror, "App.tsx")) else ""
    for path in files:
        if path.startswith("pages/") and path.endswith(".tsx") and not re.search(r"\.(pageLayout|__example)\.tsx$", path):
            if f'"./{path}"' not in app: notes.append(f"route missing in floot/App.tsx for {path}")
    # Dependencies: floot/package.json must carry Floot's pins; native plugins must also be in the root package.json.
    fpkg = json.loads(read(os.path.join(mirror, "package.json"))).get("dependencies", {}) if deps else {}
    rpkg = json.loads(read(os.path.join(mirror, "..", "package.json"))).get("dependencies", {}) if deps else {}
    for name, ver in sorted(deps.items()):
        if fpkg.get(name) != ver: notes.append(f"floot/package.json: {name} is {fpkg.get(name)}, Floot has {ver}")
        if "capacitor" in name and rpkg.get(name) != ver:
            notes.append(f"native plugin {name}@{ver} not pinned in root package.json (add it, run cap sync, re-check patches/)")
    # iOS calls the live web backend, so shipping Floot work the web hasn't published can break it.
    state = unpublished(history) if history else None
    if state is None: notes.append("publish state unknown: add static/__dev/history.md to the dumps")
    elif state and not allow_unpublished:
        notes.append("Floot has work newer than the last web publish: publish the web first, or rerun with --allow-unpublished")
    return dict(published={None: "unknown", False: "yes, nothing newer than the last web publish", True: "no, Floot has unpublished work"}[state], version=version, listed=len(files), compared=len(files) - len(problems) - len(size_only),
                size_only=size_only, problems=problems, added=added, changed=changed, removed=removed, notes=notes)


def report(r):
    real = r["added"] + r["changed"] + r["removed"] + r["notes"]
    out = [f"## Floot mirror drift report", "",
           f"Floot source version `{r['version']}`: {r['listed']} files listed, {r['compared']} compared by content, "
           f"{len(r['size_only'])} by size only. Web published at this version: {r['published']}.", "",
           f"**Result: {'incomplete Floot input, re-read the files below' if r['problems'] else str(len(real)) + ' real differences'}**", ""]
    for key, title in (("problems", "Incomplete Floot input (not compared)"), ("added", "Added in Floot"),
                       ("changed", "Changed in Floot"), ("removed", "Removed from Floot (still in floot/)"),
                       ("notes", "Wiring to check"), ("size_only", "Compared by size only (over Floot's 40k-char per-file read cap)")):
        if r[key]: out += [f"### {title} ({len(r[key])})"] + [f"- `{x}`" if key not in ("problems", "notes") else f"- {x}" for x in r[key]] + [""]
    out.append("Ignored on purpose: the platform `@layer base` block in base.css, blank lines at either end of a file, env.json and the export's shell files.")
    return "\n".join(out), (2 if r["problems"] else 1 if real else 0)


def self_test():
    dump = ("a.tsx — lines 1-3 of 3 (version: 7)\n     1\tx\n     2\t\ty\n     3\t\n"
            "b.css — lines 1-1 of 1 (version: 7)\n     1\tz\n")
    d = parse_dump(dump)
    assert d["a.tsx"] == ("x\n\ty\n", "7", True) and d["b.css"][0] == "z"
    assert parse_dump(json.dumps([{"type": "text", "text": dump}]))["a.tsx"][0] == "x\n\ty\n"
    h = parse_dump(json.dumps([{"type": "text", "text": "# Project history\nintro\n── Published x ──"}, {"type": "text", "text": dump}]))
    assert h["static/__dev/history.md"][0].endswith("── Published x ──") and h["a.tsx"][0] == "x\n\ty\n"
    assert parse_dump("d.ts — lines 1-2 of 2 (version: 7)\n     1\tq\n... (output capped at 40000 chars — re-read)\n")["d.ts"][2] is False
    assert parse_dump("c.ts — lines 1-2 of 9 (version: 7)\n     1\tq\n")["c.ts"][2] is False  # partial read
    css = ":root{--a:1}"
    assert same("base.css", css, css + "\n/* kept */\n@layer base {\n  :root{--b:2}\n}\n")
    assert not same("base.css", css, css + "\n.extra{}\n")
    assert same("base.css", css, "\n" + css + "\n@layer base {}\n") and same("a.ts", "x\n", "\nx")
    assert not same("x.css", css, css + "\n@layer base {}\n")
    assert base_css_tail(css + "\n/* kept */\n@layer base { a{} }\n").startswith("/* kept */")
    f, deps, v = parse_listing("version: 9\nbase.css (12 chars)\ndependencies: a@1.0.0, @x/y@2.0.0 — full map")
    assert f == {"base.css": 12} and deps == {"a": "1.0.0", "@x/y": "2.0.0"} and v == "9"
    assert unpublished("# Project history\nintro\n\n── Published 2026 ──\n## Checkpoint: x") is False
    assert unpublished("# Project history\n\n## Checkpoint: y\n── Published") is True
    assert unpublished("# Project history\n- 2026 · updated a\n── Published") is True
    print("self-test ok")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--listing"); ap.add_argument("--dumps"); ap.add_argument("--write", action="store_true")
    ap.add_argument("--allow-unpublished", action="store_true")
    ap.add_argument("--mirror", default=os.path.join(ROOT, "floot")); ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test: self_test(); sys.exit(0)
    if not (a.listing and a.dumps): ap.error("--listing and --dumps are required")
    text, code = report(check(a.listing, a.dumps, a.mirror, a.write, a.allow_unpublished))
    print(text)
    sys.exit(code)
